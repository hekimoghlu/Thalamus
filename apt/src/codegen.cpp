std::string verilog_regmap() {
    std::ostringstream os;
    os << banner("//", "apt_regmap.vh - CSR word addresses");
    for (const auto& r : regmap::kRegs)
        os << "localparam [6:0] A_" << r.name << std::string(16 - r.name.size(), ' ') << "= 7'h"
           << hex8(r.addr) << ";  // " << r.description << "\n";
    return os.str();
}

std::string verilog_csr_logic() {
    std::ostringstream os;
    os << banner("//", "apt_csr.vh - CSR write decode and reset values");
    os << "function is_rw;\n    input [6:0] a;\n    begin\n        case (a)\n";
    bool first = true;
    for (const auto& r : regmap::kRegs) {
        if (r.access != regmap::Access::RW) continue;
        os << (first ? "            " : ",\n            ") << "A_" << r.name;
        first = false;
    }
    os << ": is_rw = 1'b1;\n            default: is_rw = 1'b0;\n        endcase\n    end\nendfunction\n\n"
       << "task csr_reset;\n    integer k;\n    begin\n        for (k = 0; k < 128; k = k + 1) mem[k] <= 32'd0;\n";
    for (const auto& r : regmap::kRegs)
        if (r.access == regmap::Access::RW) os << "        mem[A_" << r.name << "] <= RST_" << r.name << ";\n";
    os << "    end\nendtask\n";
    return os.str();
}

std::string verilog_params(const core::Config& c, const HardwareTiming& t) {
    std::ostringstream os;
    os << banner("//", "apt_params.vh - CSR reset values and hardware timing");
    os << "localparam [31:0] DEVICE_ID      = 32'h" << hex32(regmap::kDeviceId) << ";\n"
       << "localparam [31:0] RTL_VERSION    = 32'h" << hex32(regmap::kVersion) << ";\n"
       << "localparam integer CLK_HZ        = " << t.clk_hz << ";\n"
       << "localparam integer CTRL_HZ       = " << t.ctrl_hz << ";\n"
       << "localparam integer PWM_PERIOD    = " << core::CoreModel::kPwmPeriod << ";\n"
       << "localparam integer UART_DIV      = " << t.uart_div << ";\n"
       << "localparam integer ADC_SCLK_HALF = " << t.adc_sclk_half << ";\n"
       << "localparam integer ADC_CONV_CYC  = " << t.adc_conv_cycles << ";\n"
       << "localparam integer ADC_TIMEOUT   = " << t.adc_timeout_cycles << ";\n"
       << "localparam integer PWM_DEADTIME  = " << t.pwm_deadtime_cycles << ";\n\n";
    for (const auto& r : regmap::kRegs) {
        if (r.access != regmap::Access::RW) continue;
        os << "localparam [31:0] RST_" << r.name << std::string(16 - r.name.size(), ' ') << "= 32'h"
           << hex32(reset_value(c, r.name)) << ";\n";
    }
    return os.str();
}

std::string c_regmap() {
    std::ostringstream os;
    os << banner("/*", "apt_regmap.h - CSR word addresses */");
    os << "#ifndef APT_REGMAP_H\n#define APT_REGMAP_H\n\n"
       << "#define APT_DEVICE_ID 0x" << hex32(regmap::kDeviceId) << "u\n"
       << "#define APT_RTL_VERSION 0x" << hex32(regmap::kVersion) << "u\n\n";
    for (const auto& r : regmap::kRegs)
        os << "#define APT_REG_" << r.name << std::string(16 - r.name.size(), ' ') << "0x"
           << hex8(r.addr) << "u /* " << r.description << " */\n";
    os << "\n/* CTRL bits */\n"
       << "#define APT_CTRL_ENABLE    (1u << 0)\n#define APT_CTRL_PASSIVITY (1u << 1)\n"
       << "#define APT_CTRL_STIM      (1u << 2)\n#define APT_CTRL_TELEMETRY (1u << 3)\n"
       << "#define APT_CTRL_RUN       (1u << 4)\n\n/* fault causes (STATUS[15:8]) */\n"
       << "#define APT_FAULT_ESTOP    (1u << 0)\n#define APT_FAULT_FORCE    (1u << 1)\n"
       << "#define APT_FAULT_VELOCITY (1u << 2)\n#define APT_FAULT_POSITION (1u << 3)\n"
       << "#define APT_FAULT_WATCHDOG (1u << 4)\n#define APT_FAULT_LATENCY  (1u << 5)\n"
       << "#define APT_FAULT_ADC      (1u << 6)\n\n#endif\n";
    return os.str();
}

std::string c_params(const EvidenceBase& eb, const ScheduleModel& m, const core::Config& c) {
    std::ostringstream os;
    char buf[160];
    os << banner("/*", "apt_params.h - verified dosing constants and reset configuration */");
    os << "#ifndef APT_PARAMS_H\n#define APT_PARAMS_H\n\n#include <stdint.h>\n\n";
    os << "/* --- Module M: the verified threshold dose-response ------------------------------ */\n";
    auto line = [&](const char* name, double v, const char* what) {
        std::snprintf(buf, sizeof buf, "#define %-34s %.9g /* %s */\n", name, v, what);
        os << buf;
    };
    line("APT_DOSE_THRESHOLD_REL", m.threshold(), "relative dose below which therapy buys nothing");
    line("APT_REPS_USUAL_PER_SESSION", m.reps_usual(), "verified, src 429");
    line("APT_REPS_DEVICE_PER_HOUR", m.reps_device(), "verified, src 428 (therapist-delivered rate)");
    line("APT_THRESHOLD_MIN_PER_WEEK_DEVICE", 60.0 * m.threshold_hours(m.reps_device()),
         "minutes/week at the device rate");
    line("APT_THRESHOLD_MIN_PER_WEEK_USUAL", 60.0 * m.threshold_hours(m.reps_usual()),
         "minutes/week at the usual-care rate");
    line("APT_FMUE_MCID", eb.get("fmue_mcid"), "verified, src 417");
    line("APT_GATING_ISI_MS", eb.get("somatosensory_gating_isi"), "verified, src 451");
    line("APT_GATING_RATIO", eb.get("somatosensory_gating_ratio_healthy"), "verified, src 451");
    line("APT_HAPTIC_DELAY_IMPERCEPTIBLE_MS", eb.get("haptic_delay_imperceptible"), "verified, src 442");
    os << "\n/* reset configuration (Q12.20 signals, Q8.24 coefficients) */\n"
       << "typedef struct { uint8_t addr; uint32_t value; } apt_reg_init_t;\n"
       << "static const apt_reg_init_t APT_RESET_CONFIG[] = {\n";
    for (const auto& [addr, v] : c.to_registers()) {
        if (addr == regmap::find("CTRL").addr) continue;  // armed explicitly by the session
        os << "    {0x" << hex8(addr) << "u, 0x" << hex32(v) << "u},\n";
    }
    os << "};\n#define APT_RESET_CONFIG_LEN (sizeof APT_RESET_CONFIG / sizeof APT_RESET_CONFIG[0])\n\n";
    os << "/* evidence ledger: verified parameters this suite read while generating */\n";
    for (const auto& n : eb.ledger()) os << "/*   " << n << " (src " << eb.src(n) << ") */\n";
    os << "\n#endif\n";
    return os.str();
}

std::string c_policy(const ScheduleModel& m, const ScheduleModel::Solution& s, int cs, int bs) {
    const int nc = (ScheduleModel::kNc - 1) / cs + 1, nb = (ScheduleModel::kNb - 1) / bs + 1;
    std::ostringstream os;
    char buf[128];
    os << banner("/*", "apt_policy.h - Module M optimal weekly hours, quantised for the MCU */");
    os << "#ifndef APT_POLICY_H\n#define APT_POLICY_H\n\n#include <stdint.h>\n\n";
    std::snprintf(buf, sizeof buf, "#define APT_POLICY_WEEKS %d\n#define APT_POLICY_NC %d\n#define APT_POLICY_NB %d\n",
                  ScheduleModel::kWeeks, nc, nb);
    os << buf;
    std::snprintf(buf, sizeof buf, "#define APT_POLICY_C_MIN %.9gf\n#define APT_POLICY_C_MAX 1.0f\n",
                  m.ceiling_floor());
    os << buf;
    std::snprintf(buf, sizeof buf, "#define APT_POLICY_BUDGET_H %.9gf\n#define APT_POLICY_REPS_PER_H %.9gf\n",
                  s.budget, s.reps_per_hour);
    os << buf;
    os << "/* hours per week x 4, indexed [week][ceiling bin][budget bin] */\n"
       << "static const uint8_t APT_POLICY_Q4[APT_POLICY_WEEKS][APT_POLICY_NC][APT_POLICY_NB] = {\n";
    for (int t = 0; t < ScheduleModel::kWeeks; ++t) {
        os << "  {";
        for (int ic = 0; ic < ScheduleModel::kNc; ic += cs) {
            os << "{";
            for (int ib = 0; ib < ScheduleModel::kNb; ib += bs)
                os << int(s.hours_at(t, ic, ib) * 4.0f + 0.5f) << (ib + bs < ScheduleModel::kNb ? "," : "");
            os << "}" << (ic + cs < ScheduleModel::kNc ? "," : "");
        }
        os << "}" << (t + 1 < ScheduleModel::kWeeks ? ",\n" : "\n");
    }
    os << "};\n\n#endif\n";
    return os.str();
}

std::vector<std::filesystem::path> emit_all(const std::filesystem::path& root, const EvidenceBase& eb) {
    const auto cfg = core::Config::from_design(core::DesignPoint{});
    ScheduleModel m(eb, RecoveryParams::load_default(), SensitiveWindow::fit(eb));
    m.calibrate_scale(eb);
    const auto sol = m.solve(m.reps_device(), 60.0);
    std::vector<std::pair<std::filesystem::path, std::string>> files = {
        {root / "rtl/generated/apt_regmap.vh", verilog_regmap()},
        {root / "rtl/generated/apt_params.vh", verilog_params(cfg, HardwareTiming{})},
        {root / "rtl/generated/apt_csr.vh", verilog_csr_logic()},
        {root / "fw/include/apt_regmap.h", c_regmap()},
        {root / "fw/include/apt_params.h", c_params(eb, m, cfg)},
        {root / "fw/include/apt_policy.h", c_policy(m, sol, 10, 4)},
    };
    std::vector<std::filesystem::path> out;
    for (auto& [p, text] : files) {
        std::filesystem::create_directories(p.parent_path());
        std::ofstream(p, std::ios::binary) << text;
        out.push_back(p);
    }
    return out;
}

