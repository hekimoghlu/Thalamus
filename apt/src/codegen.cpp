std::string hex32(std::uint32_t v) {
    char b[16];
    std::snprintf(b, sizeof b, "%08X", v);
    return b;
}

std::string hex8(unsigned v) {
    char b[8];
    std::snprintf(b, sizeof b, "%02X", v & 0xFF);
    return b;
}

std::string banner(const char* comment, const char* what) {
    std::ostringstream os;
    os << comment << " " << what << "\n"
       << comment << " GENERATED by `aptctl codegen` from apt/include/apt - do not edit.\n";
    return os.str();
}

std::uint32_t reset_value(const core::Config& c, std::string_view name) {
    if (name == "CTRL") return 0;  // the device powers up disarmed, whatever the config says
    for (const auto& [addr, v] : c.to_registers())
        if (regmap::find(name).addr == addr) return v;
    return 0;
}

